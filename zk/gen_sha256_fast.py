"""Emit the bounded-integer SHA-256 compression (spliced into zk/cairo/src/sha256.cairo)."""
ROT = [2, 13, 22, 6, 11, 25, 7, 18, 17, 19]
SHR = [3, 10]
M = 0xFFFFFFFF
o = []
o.append('''// The compression below replaces Raito's, which builds each rotation from a u32 division, an
// overflowing u32 multiplication and an OR, and adds with overflow-checked u32 additions. Here
// words are bounded integers whose ranges the compiler tracks: a rotation is one division by 2^n
// plus a multiply-add that cannot overflow, a sum is exact and reduced mod 2^32 once, and no value
// is range-checked twice. Ch and Maj use the three-operation forms. Same function: checked against
// FIPS 180-4 vectors in the tests below, and against node's SHA-256 through every Merkle root the
// program recomputes. (Generated by zk/gen_sha256_fast.py, then `scarb fmt`.)

type B32 = BoundedInt<0, 0xffffffff>;
type P32 = UnitInt<0x100000000>;
const NZ_P32: NonZero<P32> = 0x100000000;
''')
for k in range(2, 8):
    o.append(f'type S{k} = BoundedInt<0, {hex(k * M)}>;')
o.append('impl AddB32B32 of AddHelper<B32, B32> {\n    type Result = S2;\n}')
for k in range(2, 7):
    o.append(f'impl AddS{k}B32 of AddHelper<S{k}, B32> {{\n    type Result = S{k + 1};\n}}')
for k in (2, 4, 6, 7):
    o.append(f'''impl RedS{k} of DivRemHelper<S{k}, P32> {{
    type DivT = BoundedInt<0, {k - 1}>;
    type RemT = B32;
}}
#[inline(always)]
fn red{k}(x: S{k}) -> u32 {{
    let (_, r) = bounded_int::div_rem(x, NZ_P32);
    upcast(r)
}}''')
o.append('''#[inline(always)]
fn b(x: u32) -> B32 {
    upcast(x)
}
''')
o.append('// rotr(x, n) = (x mod 2^n) * 2^(32 - n) + x div 2^n; shr(x, n) = x div 2^n.')
for n in ROT + SHR:
    d, m = 1 << n, 1 << (32 - n)
    o.append(f'''const NZ{n}: NonZero<UnitInt<{hex(d)}>> = {hex(d)};
impl D{n} of DivRemHelper<u32, UnitInt<{hex(d)}>> {{
    type DivT = BoundedInt<0, {hex(m - 1)}>;
    type RemT = BoundedInt<0, {hex(d - 1)}>;
}}''')
    if n in ROT:
        hi = (d - 1) * m
        o.append(f'''const U{n}: UnitInt<{hex(m)}> = {hex(m)};
impl M{n} of MulHelper<BoundedInt<0, {hex(d - 1)}>, UnitInt<{hex(m)}>> {{
    type Result = BoundedInt<0, {hex(hi)}>;
}}
impl A{n} of AddHelper<BoundedInt<0, {hex(hi)}>, BoundedInt<0, {hex(m - 1)}>> {{
    type Result = B32;
}}
#[inline(always)]
fn rotr{n}(x: u32) -> u32 {{
    let (q, r) = bounded_int::div_rem(x, NZ{n});
    let s: B32 = bounded_int::add(bounded_int::mul(r, U{n}), q);
    upcast(s)
}}''')
    else:
        o.append(f'''#[inline(always)]
fn shr{n}(x: u32) -> u32 {{
    let (q, _) = bounded_int::div_rem(x, NZ{n});
    upcast(q)
}}''')
o.append('''
fn sha256_inner(data: Span<u32>, h: Sha256State) -> Sha256State {
    let mut w = create_message_schedule(data);
    let mut g = h;
    let mut k = k.span();

    while let Option::Some(ki) = k.pop_front() {
        let wi = w.pop_front().unwrap();
        g = compression(*wi, *ki, g);
    }

    let (h0, h1, h2, h3, h4, h5, h6, h7) = h;
    let (g0, g1, g2, g3, g4, g5, g6, g7) = g;
    (
        red2(bounded_int::add(b(h0), b(g0))), red2(bounded_int::add(b(h1), b(g1))),
        red2(bounded_int::add(b(h2), b(g2))), red2(bounded_int::add(b(h3), b(g3))),
        red2(bounded_int::add(b(h4), b(g4))), red2(bounded_int::add(b(h5), b(g5))),
        red2(bounded_int::add(b(h6), b(g6))), red2(bounded_int::add(b(h7), b(g7))),
    )
}

#[inline(always)]
fn compression(wi: u32, ki: u32, h: Sha256State) -> Sha256State {
    let (a, bb, c, d, e, f, g, hh) = h;
    let s1 = rotr6(e) ^ rotr11(e) ^ rotr25(e);
    let ch = g ^ (e & (f ^ g));
    let t: S5 = bounded_int::add(
        bounded_int::add(bounded_int::add(bounded_int::add(b(hh), b(s1)), b(ch)), b(ki)), b(wi),
    );
    let s0 = rotr2(a) ^ rotr13(a) ^ rotr22(a);
    let maj = (a & bb) | (c & (a | bb));
    let new_a = red7(bounded_int::add(bounded_int::add(t, b(s0)), b(maj)));
    let new_e = red6(bounded_int::add(t, b(d)));
    (new_a, a, bb, c, new_e, e, f, g)
}

fn create_message_schedule(data: Span<u32>) -> Span<u32> {
    let mut result: Array<u32> = data.into();
    for i in 16..64_usize {
        let x = *result[i - 15];
        let y = *result[i - 2];
        let s0 = rotr7(x) ^ rotr18(x) ^ shr3(x);
        let s1 = rotr17(y) ^ rotr19(y) ^ shr10(y);
        let sum: S4 = bounded_int::add(
            bounded_int::add(bounded_int::add(b(*result[i - 16]), b(s0)), b(*result[i - 7])), b(s1),
        );
        result.append(red4(sum));
    }
    result.span()
}
''')
print('\n'.join(o))
